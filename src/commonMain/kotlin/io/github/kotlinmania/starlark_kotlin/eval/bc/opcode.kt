/// Instruction opcode.

import kotlin.reflect.KClass

// Placeholder types referenced from other modules
// These will be replaced with real imports as the port progresses
// BcInstr is defined in repr.kt

/// Callback for the `dispatch` function.
interface BcOpcodeHandler<R> {
    fun <I : BcInstr> handle(instrClass: KClass<I>): R
}

/// Callback for the `dispatch_all` function.
interface BcOpcodeAllHandler {
    fun <I : BcInstr> handle(instrClass: KClass<I>, opcode: BcOpcode)
}

/// Bytecode instruction opcode.
enum class BcOpcode {
    Const,
    LoadLocal,
    LoadLocalCaptured,
    LoadModule,
    Mov,
    StoreLocalCaptured,
    StoreModule,
    StoreModuleAndExport,
    Unpack,
    ArrayIndex,
    SetArrayIndex,
    ArrayIndexSet,
    Slice,
    ObjectField,
    SetObjectField,
    Eq,
    EqConst,
    EqPtr,
    EqStr,
    EqInt,
    Not,
    Minus,
    Plus,
    BitNot,
    Less,
    Greater,
    LessOrEqual,
    GreaterOrEqual,
    In,
    Add,
    AddAssign,
    Sub,
    Multiply,
    Percent,
    PercentSOne,
    FormatOne,
    Divide,
    FloorDivide,
    BitAnd,
    BitOr,
    BitOrAssign,
    BitXor,
    LeftShift,
    RightShift,
    Len,
    Type,
    TypeIs,
    IsInstance,
    TupleNPop,
    ListNew,
    ListNPop,
    ListOfConsts,
    DictNew,
    DictNPop,
    DictOfConsts,
    DictConstKeys,
    ComprListAppend,
    ComprDictInsert,
    CheckType,
    Br,
    IfBr,
    IfNotBr,
    Iter,
    Continue,
    Break,
    IterStop,
    Return,
    ReturnConst,
    ReturnCheckType,
    Call,
    CallPos,
    CallFrozenDef,
    CallFrozenDefPos,
    CallFrozenNative,
    CallFrozenNativePos,
    CallFrozen,
    CallFrozenPos,
    CallMethod,
    CallMethodPos,
    CallMaybeKnownMethod,
    CallMaybeKnownMethodPos,
    Def,
    ArrayIndex2,
    PossibleGc,
    End,
    ;

    companion object {
        /// Opcode count.
        val COUNT: Int = entries.size

        /// Invoke a callback parameterized by instruction type for each opcode.
        fun dispatchAll(handler: BcOpcodeAllHandler) {
            // In Rust this is generated by proc macro.
            // In Kotlin we iterate all entries.
            doDispatchAll(handler)
        }

        private fun doDispatchAll(handler: BcOpcodeAllHandler) {
            for (opcode in entries) {
                handler.handle(BcInstr::class, opcode)
            }
        }

        /// Get opcode by opcode number.
        fun byNumber(n: UInt): BcOpcode? {
            val entries = entries
            val index = n.toInt()
            return if (index in entries.indices) {
                entries[index]
            } else {
                null
            }
        }

        /// Get bytecode opcode for the instruction.
        fun forInstr(instrClass: KClass<out BcInstr>): BcOpcode {
            var found: BcOpcode? = null
            dispatchAll(object : BcOpcodeAllHandler {
                override fun <I : BcInstr> handle(klass: KClass<I>, opcode: BcOpcode) {
                    if (klass == instrClass) {
                        check(found == null)
                        found = opcode
                    }
                }
            })
            return found
                ?: throw IllegalStateException("No opcode for instruction ${instrClass.simpleName}")
        }
    }

    /// Invoke a callback parameterized by instruction type depending on this opcode.
    fun <R> dispatch(handler: BcOpcodeHandler<R>): R {
        // Call dispatch generated by proc macro equivalent.
        return doDispatch(handler)
    }

    private fun <R> doDispatch(handler: BcOpcodeHandler<R>): R {
        return handler.handle(BcInstr::class)
    }

    /// Check if this opcode is a call instruction.
    fun isCall(): Boolean {
        return when (this) {
            Call,
            CallPos,
            CallFrozenDef,
            CallFrozenDefPos,
            CallFrozenNative,
            CallFrozenNativePos,
            CallFrozen,
            CallFrozenPos,
            CallMethod,
            CallMethodPos,
            CallMaybeKnownMethod,
            CallMaybeKnownMethodPos -> true
            else -> false
        }
    }
}
