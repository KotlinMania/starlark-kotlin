/** Instruction opcode. */

import kotlin.reflect.KClass
import io.github.kotlinmania.starlark.eval.bc.BcInstr
import io.github.kotlinmania.starlark.eval.bc.BcInstrRepr

/** Callback for the `dispatch` function. */
internal interface BcOpcodeHandler<R> {
    fun <I : BcInstr<*>> handle(instrClass: KClass<I>): R
}

/** Callback for the `dispatchAll` function. */
internal interface BcOpcodeAllHandler {
    fun <I : BcInstr<*>> handle(instrClass: KClass<I>, opcode: BcOpcode)
}

/** Bytecode instruction opcode. */
internal enum class BcOpcode {
    Const,
    LoadLocal,
    LoadLocalCaptured,
    LoadModule,
    Mov,
    StoreLocalCaptured,
    StoreModule,
    StoreModuleAndExport,
    Unpack,
    ArrayIndex,
    SetArrayIndex,
    ArrayIndexSet,
    Slice,
    ObjectField,
    SetObjectField,
    Eq,
    EqConst,
    EqPtr,
    EqStr,
    EqInt,
    Not,
    Minus,
    Plus,
    BitNot,
    Less,
    Greater,
    LessOrEqual,
    GreaterOrEqual,
    In,
    Add,
    AddAssign,
    Sub,
    Multiply,
    Percent,
    PercentSOne,
    FormatOne,
    Divide,
    FloorDivide,
    BitAnd,
    BitOr,
    BitOrAssign,
    BitXor,
    LeftShift,
    RightShift,
    Len,
    Type,
    TypeIs,
    IsInstance,
    TupleNPop,
    ListNew,
    ListNPop,
    ListOfConsts,
    DictNew,
    DictNPop,
    DictOfConsts,
    DictConstKeys,
    ComprListAppend,
    ComprDictInsert,
    CheckType,
    Br,
    IfBr,
    IfNotBr,
    Iter,
    Continue,
    Break,
    IterStop,
    Return,
    ReturnConst,
    ReturnCheckType,
    Call,
    CallPos,
    CallFrozenDef,
    CallFrozenDefPos,
    CallFrozenNative,
    CallFrozenNativePos,
    CallFrozen,
    CallFrozenPos,
    CallMethod,
    CallMethodPos,
    CallMaybeKnownMethod,
    CallMaybeKnownMethodPos,
    Def,
    ArrayIndex2,
    PossibleGc,
    End,
    ;

    companion object {
        /** Opcode count. */
        val COUNT: Int = values().size

        /** Invoke a callback parameterized by instruction type for each opcode. */
        fun dispatchAll(handler: BcOpcodeAllHandler) {
            doDispatchAll(handler)
        }

        private fun doDispatchAll(handler: BcOpcodeAllHandler) {
            for (opcode in values()) {
                handler.handle(BcInstr::class, opcode)
            }
        }

        /** Get opcode by opcode number. */
        fun byNumber(n: UInt): BcOpcode? {
            val entries = values()
            val index = n.toInt()
            return if (index in entries.indices) {
                entries[index]
            } else {
                null
            }
        }

        /** Get bytecode opcode for the instruction. */
        fun forInstr(target: KClass<out BcInstr<*>>): BcOpcode {
            var found: BcOpcode? = null
            dispatchAll(object : BcOpcodeAllHandler {
                override fun <I : BcInstr<*>> handle(instrClass: KClass<I>, opcode: BcOpcode) {
                    if (instrClass.equals(target)) {
                        check(found == null)
                        found = opcode
                    }
                }
            })
            return found
                ?: throw IllegalStateException("No opcode for instruction ${target.simpleName}")
        }
    }

    /** Invoke a callback parameterized by instruction type depending on this opcode. */
    fun <R> dispatch(handler: BcOpcodeHandler<R>): R {
        // Call dispatch generated by proc macro equivalent.
        return doDispatch(handler)
    }

    private fun <R> doDispatch(handler: BcOpcodeHandler<R>): R {
        return handler.handle(BcInstr::class)
    }

    /** Size of instruction representation. */
    fun sizeOfRepr(): Int {
        val handler = object : BcOpcodeHandler<Int> {
            override fun <I : BcInstr<*>> handle(instrClass: KClass<I>): Int {
                return BcInstrRepr.sizeOf(instrClass)
            }
        }
        return dispatch(handler)
    }

    // Bypass compiler bug: use .name == "string" instead of `this == Op`
    fun isCall(): Boolean {
        val n = this.name
        return n == "Call" ||
            n == "CallPos" ||
            n == "CallFrozenDef" ||
            n == "CallFrozenDefPos" ||
            n == "CallFrozenNative" ||
            n == "CallFrozenNativePos" ||
            n == "CallFrozen" ||
            n == "CallFrozenPos" ||
            n == "CallMethod" ||
            n == "CallMethodPos" ||
            n == "CallMaybeKnownMethod" ||
            n == "CallMaybeKnownMethodPos"
    }
}
